def load_ecd_data(data_dir):
    """
    加载ECD数据集中 label=1 的对话，提取客户侧文本

    数据格式: 序号 \t 标签 \t 对话轮1 \t 对话轮2 \t ... \t 对话轮N
    其中对话轮之间用空格分词，客户和客服交替发言

    Returns:
        List[str]: 客户侧文本列表（去词间空格后的完整句子）
    """
    texts = []
    seen = set()
    file_list = ["train", "valid", "test"]

    for fname in file_list:
        fpath = os.path.join(data_dir, fname)
        if not os.path.exists(fpath):
            continue

        with open(fpath, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue

                parts = line.split("\t")
                if len(parts) < 3:
                    continue

                label = parts[1].strip()
                if label != "1":
                    continue

                # 偶数索引(2,4,6...) 为客户发言
                customer_utterances = []
                for i in range(2, len(parts), 2):
                    words = parts[i].strip()
                    if words:
                        customer_utterances.append(words)

                full_text = "".join(customer_utterances)
                if full_text and full_text not in seen:
                    seen.add(full_text)
                    texts.append(full_text)

    return texts


