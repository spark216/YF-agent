# 2. 数据清洗与合成
# ============================================================

def clean_text(text):
    """清洗单条文本"""
    text = text.strip()
    text = re.sub(r"\s+", "", text)
    if len(text) < 2:
        return None
    return text


def process_all_data(ecd_dir):
    """
    汇总所有数据源，完成清洗和去重

    Returns:
        List[Dict]: [{"text": str, "source": str, "intent": str}, ...]
    """
    print("=" * 60)
    print("  酒店客服意图识别 - 数据预处理")
    print("=" * 60)

    # 1) 加载ECD电商客服数据
    print("\n[1/3] 加载ECD电商客服数据...")
    ecd_texts = load_ecd_data(ecd_dir)
    print(f"  ECD数据: {len(ecd_texts)} 条客户对话文本")

    # 2) 合成酒店领域意图数据
    print("\n[2/3] 生成酒店领域意图数据...")
    hotel_data = synthesize_hotel_data()
    hotel_texts = []
    for intent, texts in hotel_data.items():
        print(f"  [{intent}] {len(texts)} 条")
        for t in texts:
            hotel_texts.append({"text": t, "source": "synthetic", "intent": intent})
    print(f"  合成数据总计: {len(hotel_texts)} 条")

    # 3) 清洗
    print("\n[3/3] 数据清洗...")
    cleaned_ecd = []
    for t in ecd_texts:
        c = clean_text(t)
        if c:
            cleaned_ecd.append({"text": c, "source": "ecd"})

    cleaned_hotel = []
    for item in hotel_texts:
        c = clean_text(item["text"])
        if c:
            cleaned_hotel.append({"text": c, "source": item["source"], "intent": item["intent"]})

    print(f"  ECD清洗后: {len(cleaned_ecd)} 条")
    print(f"  合成清洗后: {len(cleaned_hotel)} 条")

    # 去重
    all_texts = cleaned_ecd + cleaned_hotel
    seen = set()
    unique_data = []
    for item in all_texts:
        if item["text"] not in seen:
            seen.add(item["text"])
            unique_data.append(item)

    print(f"  去重后总计: {len(unique_data)} 条")

    return unique_data


# ============================================================
# 3. 构建标注数据集
# ============================================================

def build_labeled_dataset(data):
    """
    从合成数据中提取全部标注数据

    ECD 数据无正确意图标签，不参与训练集构建
    """
    print("\n[采样] 提取全部合成标注数据...")

    unique_intents = config.INTENT_NAMES
    selected = []

    for intent in unique_intents:
        intent_samples = [
            {"text": t["text"], "intent": t["intent"]}
            for t in data
            if isinstance(t, dict) and t.get("intent") == intent
        ]
        selected.extend(intent_samples)
        print(f"  [{intent}] {len(intent_samples)} 条")

    print(f"  标注数据集: 总计 {len(selected)} 条")
    return selected


# ============================================================
# 4. 保存结果
# ============================================================

def save_results(cleaned_data, sampled_data):
    """保存清洗数据和标注数据集"""
    os.makedirs(config.DATA_PREPROC_DIR, exist_ok=True)

    with open(config.CLEANED_DATA_PATH, "w", encoding="utf-8") as f:
        json.dump(cleaned_data, f, ensure_ascii=False, indent=2)
    print(f"\n  清洗数据已保存: {config.CLEANED_DATA_PATH}")

    with open(config.SAMPLED_LABELS_PATH, "w", encoding="utf-8") as f:
        json.dump(sampled_data, f, ensure_ascii=False, indent=2)
    print(f"  标注数据集已保存: {config.SAMPLED_LABELS_PATH}")


