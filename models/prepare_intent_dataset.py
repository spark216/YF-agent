# Main
# ============================================================

def main():
    # Step 1: 数据处理
    cleaned_data = process_all_data(config.ECD_DATA_DIR)

    if len(cleaned_data) < 100:
        print(f"\n错误: 数据量过少 ({len(cleaned_data)}条)，请检查数据路径!")
        return

    print(f"\n  总数据量: {len(cleaned_data)} 条")

    # Step 2: 构建标注集
    sampled_data = build_labeled_dataset(cleaned_data)

    # Step 3: 保存
    save_results(cleaned_data, sampled_data)

    print("\n" + "=" * 60)
    print("  数据预处理完成!")
    print(f"  总数据: {len(cleaned_data)} 条 (含 ECD + 合成)")
    print(f"  标注数据: {len(sampled_data)} 条 (全部合成数据)")
    print("=" * 60)
    print("\n  下一步: 运行 python train_intent_classifier.py 进行模型微调")


if __name__ == "__main__":
    main()
